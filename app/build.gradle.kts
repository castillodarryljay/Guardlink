val buildDirFile: File = layout.buildDirectory.asFile.get()
val rootDirFile: File = rootDir

tasks.register("copyDebugApk") {
  val apk = buildDirFile.resolve("outputs/apk/debug/app-debug.apk")
  val destination = rootDirFile.resolve("app-debug.apk")
  doLast {
    if (apk.exists()) {
      apk.copyTo(destination, overwrite = true)
      println("Successfully copied APK to: ${destination.absolutePath}")
    } else {
      println("APK not found at: ${apk.absolutePath}")
    }
  }
}

tasks.configureEach {
  if (name == "assembleDebug") {
    finalizedBy("copyDebugApk")
  }
}
