val base64File = file("${rootDir}/debug.keystore.base64")
val keystoreFile = file("${rootDir}/debug.keystore")
if (base64File.exists() && !keystoreFile.exists()) {
    try {
        val base64Text = base64File.readText().trim()
        val decodedBytes = Base64.getDecoder().decode(base64Text)
        keystoreFile.writeBytes(decodedBytes)
        logger.lifecycle("Successfully decoded debug.keystore from base64 at build configuration time!")
    } catch (e: Exception) {
        logger.error("Failed to decode debug.keystore: ${e.message}")
    }
}

